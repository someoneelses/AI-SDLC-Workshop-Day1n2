import {test,expect} from '@playwright/test';import {register,createTemplate,createTag,createTodo} from './helpers';
test('using a template creates incomplete subtasks',async({page})=>{await register(page);const t=await createTemplate(page,{name:'Checklist',title_template:'New task',subtasks:[{title:'Step',position:0,completed:true}]});const result=await (await page.request.post(`/api/templates/${t.id}/use`)).json();expect(result.subtasks[0].title).toBe('Step');expect(result.subtasks[0].completed).toBe(false)});

test('saving and editing templates preserves selected tags from tasks and drafts',async({page})=>{
  await register(page);
  const tag=await createTag(page,'Work');
  const task=await createTodo(page,'Tagged task',{tagIds:[tag.id],priority:'high'});
  await page.reload();
  await page.getByRole('button',{name:'Save Tagged task as template'}).click();
  let dialog=page.getByRole('dialog',{name:'Save as template'});
  await expect(dialog.getByLabel('Work')).toBeChecked();
  await dialog.getByLabel('Template name').fill('Tagged template');
  await dialog.getByRole('button',{name:'Save template'}).click();
  await page.getByRole('button',{name:'Templates',exact:true}).click();
  dialog=page.getByRole('dialog',{name:'Templates'});
  await dialog.getByRole('button',{name:'Edit template Tagged template'}).click();
  dialog=page.getByRole('dialog',{name:'Edit template'});
  await expect(dialog.getByLabel('Work')).toBeChecked();
  await dialog.getByRole('button',{name:'Save template'}).click();
  await page.getByRole('button',{name:'Templates',exact:true}).click();
  await page.getByRole('dialog',{name:'Templates'}).getByRole('button',{name:'Use',exact:true}).click();
  const todos=await (await page.request.get('/api/todos')).json();
  const copied=todos.find((item:{id:number})=>item.id!==task.id);
  expect(copied.priority).toBe('high');expect(copied.tags.map((item:{id:number})=>item.id)).toEqual([tag.id]);
  await page.getByLabel('Task title').fill('Draft task');
  await page.getByRole('group',{name:'Tags'}).getByLabel('Work').check();
  await page.getByRole('button',{name:'Save as template',exact:true}).click();
  dialog=page.getByRole('dialog',{name:'Save as template'});
  await expect(dialog.getByLabel('Work')).toBeChecked();
  await dialog.getByRole('button',{name:'Save template'}).click();
  const templates=await (await page.request.get('/api/templates')).json();
  const draft=templates.find((item:{name:string})=>item.name==='Draft task');
  const created=await (await page.request.post('/api/templates/'+draft.id+'/use')).json();
  expect(created.tags.map((item:{id:number})=>item.id)).toEqual([tag.id]);
});

test('template tag changes are isolated, atomic and follow tag deletion',async({page,browser})=>{
  await register(page);
  const first=await createTag(page,'First');const second=await createTag(page,'Second');
  const template=await createTemplate(page,{name:'Reusable',title_template:'Task',tagIds:[first.id]});
  const path='/api/templates/'+template.id;
  const context=await browser.newContext({baseURL:new URL(page.url()).origin});const other=await context.newPage();
  await register(other);const foreign=await createTag(other,'Private');
  expect((await page.request.post('/api/templates',{data:{name:'Bad',title_template:'Bad',tagIds:[foreign.id]}})).status()).toBe(400);
  expect((await page.request.put(path,{data:{name:'Changed',tagIds:[second.id,foreign.id]}})).status()).toBe(400);
  let templates=await (await page.request.get('/api/templates')).json();
  expect(templates).toHaveLength(1);expect(templates[0].name).toBe('Reusable');expect(templates[0].tagIds).toEqual([first.id]);
  expect((await page.request.put(path,{data:{description:'keep tags'}})).ok()).toBeTruthy();
  expect((await page.request.put(path,{data:{tagIds:[first.id,second.id]}})).ok()).toBeTruthy();
  expect((await page.request.put('/api/tags/'+first.id,{data:{name:'Renamed'}})).ok()).toBeTruthy();
  let created=await (await page.request.post(path+'/use')).json();
  expect(created.tags.map((tag:{name:string})=>tag.name)).toEqual(['Renamed','Second']);
  expect((await page.request.delete('/api/tags/'+first.id)).ok()).toBeTruthy();
  templates=await (await page.request.get('/api/templates')).json();expect(templates[0].tagIds).toEqual([second.id]);
  expect((await page.request.put(path,{data:{tagIds:[]}})).ok()).toBeTruthy();
  created=await (await page.request.post(path+'/use')).json();expect(created.tags).toEqual([]);
  await context.close();
});
